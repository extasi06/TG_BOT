def get_template(error_type: str) -> dict[str, str]:
    return FEEDBACK_TEMPLATES.get(error_type, FEEDBACK_TEMPLATES["calculation_error"])


def template_meta() -> dict[str, Any]:
    """Метаданные для отчёта и анкетирования."""
    return {
        code: {
            "title": t["title"],
            "has_rule": bool(t.get("rule")),
            "has_direction": bool(t.get("direction")),
            "spoiler_safe": "готового ответа" in t.get("quality_note", "").lower()
            or "не содержит" in t.get("quality_note", "").lower()
            or "без" in t.get("quality_note", "").lower(),
        }
        for code, t in FEEDBACK_TEMPLATES.items()
    }